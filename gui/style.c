static bool s_style_initialized = false;
static bool s_has_css_error = false;

static void on_parsing_error(GtkCssProvider *provider, GtkCssSection *section,
                             const GError *error, gpointer user_data) {
    (void)provider;
    (void)section;
    (void)user_data;
    s_has_css_error = true;
    fprintf(stderr, "WARNING: GTK CSS Parsing Error: %s\n", error ? error->message : "unknown");
}

bool gui_style_init(void) {
    GdkDisplay *display = gdk_display_get_default();
    if (!display) return false;

    /* Request dark theme at GTK display settings level */
    GtkSettings *settings = gtk_settings_get_for_display(display);
    if (settings) {
        g_object_set(settings, "gtk-application-prefer-dark-theme", TRUE, NULL);
    }

    GtkCssProvider *provider = gtk_css_provider_new();
    if (!provider) return false;

    s_has_css_error = false;
    g_signal_connect(provider, "parsing-error", G_CALLBACK(on_parsing_error), NULL);

    char *combined = g_strconcat(GUI_STYLE_CSS_PART1, GUI_STYLE_CSS_PART2, NULL);
    gtk_css_provider_load_from_data(provider, combined, -1);
    g_free(combined);

    gtk_style_context_add_provider_for_display(
        display,
        GTK_STYLE_PROVIDER(provider),
        GTK_STYLE_PROVIDER_PRIORITY_USER
    );
    g_object_unref(provider);
    s_style_initialized = true;
    return true;
}

bool gui_style_is_initialized(void) {
    return s_style_initialized && !s_has_css_error;
}

bool gui_style_has_parsing_error(void) {
    return s_has_css_error;
}
